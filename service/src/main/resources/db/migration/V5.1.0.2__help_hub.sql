CREATE TABLE help_request (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(255) NOT NULL REFERENCES project_definition(project_id) ON UPDATE CASCADE ON DELETE CASCADE,
    user_id VARCHAR(255) NOT NULL REFERENCES user_attrs(user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    scope_type VARCHAR(32) NOT NULL CHECK (scope_type IN ('PROJECT', 'SUBJECT', 'SKILL')),
    skill_ref_id INTEGER REFERENCES skill_definition(id) ON DELETE SET NULL,
    title VARCHAR(255) NOT NULL,
    body TEXT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'RESOLVED')),
    resolved_by_user_id VARCHAR(255),
    resolved_by_role VARCHAR(32) CHECK (resolved_by_role IN ('STUDENT', 'STAFF')),
    resolved_on TIMESTAMP WITHOUT TIME ZONE,
    -- unused in the MVP; present so publishing Q&As does not need another migration
    published_on TIMESTAMP WITHOUT TIME ZONE,
    published_by VARCHAR(255),
    published_title VARCHAR(255),
    published_body TEXT,
    created TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    updated TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_help_request_project_status ON help_request(project_id, status);
CREATE INDEX idx_help_request_user_project ON help_request(user_id, project_id);

CREATE TABLE help_reply (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    help_request_id INTEGER NOT NULL REFERENCES help_request(id) ON DELETE CASCADE,
    author_user_id VARCHAR(255) NOT NULL,
    author_role VARCHAR(32) NOT NULL CHECK (author_role IN ('STUDENT', 'ADMIN', 'APPROVER')),
    body TEXT NOT NULL,
    -- unused in the MVP
    published BOOLEAN NOT NULL DEFAULT FALSE,
    created TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    edited_on TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX idx_help_reply_request ON help_reply(help_request_id);

